"""Hybrid-recipe recall eval over ministerial diary engagements (reference_extraction_hybrid_recipe).

Graduated from pipeline_sandbox/minister_meetings/ 2026-08-01, alongside
extractors/diary_entry_classify.py (tier 1 of the classifier it evaluates; MODEL_GATES there
cites this eval's verify_sample.json). A = diary_entry_classify.py's ordered keyword rules;
its "other" class IS the declared recall gap. B = TF-IDF+LinearSVC trained on A's 8 labeled
classes, applied to the "other" bucket -> ranked reclassification queue for P(True) labeling.
Also: dedup count (minister+date+subject) and per-department month completeness — the two
traps the council-minutes run proved recur.

Outputs (this dir): diary_tolabel.json (top-confidence queue sample) ·
MINISTER_MEETINGS_QUALITY.md (Completeness + Recall sections).
Usage: python diary_recall_probe.py
"""

from __future__ import annotations

import json
from pathlib import Path

import polars as pl

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
P = ROOT / "data/gold/parquet/ministerial_diary_engagements.parquet"


def main() -> int:
    df = pl.read_parquet(P)
    n = len(df)

    # dedup trap
    dups = n - df.select(["minister", "entry_date", "subject"]).unique().height

    # completeness: per department, months with >=1 entry vs months in its own span
    comp = (
        df.filter(pl.col("entry_date").is_not_null())
        .with_columns(pl.col("entry_date").dt.strftime("%Y-%m").alias("ym"))
        .group_by("department")
        .agg(
            pl.col("ym").n_unique().alias("months_covered"),
            pl.col("entry_date").min().alias("first"),
            pl.col("entry_date").max().alias("last"),
            pl.len().alias("entries"),
        )
        .with_columns(
            (
                (pl.col("last").dt.year() - pl.col("first").dt.year()) * 12
                + (pl.col("last").dt.month() - pl.col("first").dt.month())
                + 1
            ).alias("months_span")
        )
        .sort("entries", descending=True)
    )

    # B: train on labeled classes, rank "other"
    lab = df.filter(
        (pl.col("entry_class") != "other") & pl.col("subject").is_not_null() & (pl.col("subject").str.len_chars() > 5)
    )
    other = df.filter(
        (pl.col("entry_class") == "other") & pl.col("subject").is_not_null() & (pl.col("subject").str.len_chars() > 5)
    )
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.svm import LinearSVC

    vec = TfidfVectorizer(ngram_range=(1, 2), max_features=60000, sublinear_tf=True)
    X = vec.fit_transform(lab["subject"].to_list())
    clf = LinearSVC(class_weight="balanced").fit(X, lab["entry_class"].to_list())
    Xo = vec.transform(other["subject"].to_list())
    margins = clf.decision_function(Xo)
    pred = clf.predict(Xo)
    top_margin = margins.max(axis=1)

    import numpy as np

    conf = float((top_margin > 0).sum())
    rows = []
    for cls in clf.classes_:
        idx = np.where((pred == cls) & (top_margin > 0))[0]
        idx = idx[np.argsort(-top_margin[idx])][:6]
        for i in idx:
            rows.append(
                {
                    "id": len(rows),
                    "predicted": cls,
                    "margin": round(float(top_margin[i]), 2),
                    "minister": other["minister"][int(i)],
                    "subject": other["subject"][int(i)][:200],
                }
            )
    (HERE / "diary_tolabel.json").write_text(json.dumps(rows, ensure_ascii=False, indent=0), encoding="utf-8")

    L = ["# Ministerial diary engagements — hybrid-recipe quality probe\n"]
    L.append(f"Auto-generated by diary_recall_probe.py over {n:,} gold rows (ministerial_diary_engagements.parquet).\n")
    L.append("## Completeness\n")
    L.append(
        "Denominator: months in each department's OWN first-to-last entry span "
        "(self-referential — a department that stopped publishing shows a gap only up to "
        "its last entry; true denominator = months the minister held office, join to "
        "who_was_minister for the promote-grade version). [Extracted — polars aggregation]\n"
    )
    L.append("| department | entries | first | last | months covered / span |")
    L.append("|---|---|---|---|---|")
    for r in comp.iter_rows(named=True):
        L.append(
            f"| {r['department']} | {r['entries']:,} | {r['first']} | {r['last']} | "
            f"{r['months_covered']}/{r['months_span']} |"
        )
    L.append(
        f"\nDuplicate rows (same minister+date+subject): {dups:,} of {n:,} "
        f"({100 * dups / n:.1f}%) — dedup before any promoted counts.\n"
    )
    L.append("## Recall\n")
    L.append(
        f"A's declared gap: entry_class='other' = {len(other):,} classifiable-text rows. "
        f"B (LinearSVC on A's 8 labeled classes) assigns {conf:,.0f} of them "
        f"({100 * conf / max(1, len(other)):.0f}%) to a real class with positive margin. "
        "B's precision on this queue is UNMEASURED until the P(True) sample "
        "(diary_tolabel.json) is labeled — see AB verdict in the council-minutes run: "
        "expect confounds, verify before reclassifying anything.\n"
    )
    (HERE / "MINISTER_MEETINGS_QUALITY.md").write_text("\n".join(L), encoding="utf-8")
    print(
        f"rows={n:,} dups={dups:,} other={len(other):,} svm_positive={conf:,.0f} "
        f"sample={len(rows)} -> diary_tolabel.json, MINISTER_MEETINGS_QUALITY.md",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
