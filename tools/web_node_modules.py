"""One clean web install per lockfile, linked into every planning/product worktree.

Worktrees of the private repo used to share `web/node_modules` by junctioning into another
worktree or into the primary checkout. On 2026-11-08 removing one worktree deleted packages a
second worktree was using through such a junction, and four worktrees ran against the primary
checkout's Next 16.3.8 install while their lockfile pinned 16.4.3, which gave false tsc errors.

This tool keeps installs in a store outside every worktree and outside C:/tmp, one directory per
`web/package-lock.json` (keyed by its SHA-256), each installed with `npm ci` from that exact
lockfile. A worktree's `web/node_modules` is a junction (a symlink off Windows) to the store entry
for its own lockfile, so removing a worktree removes only a link.

    python tools/web_node_modules.py status            # every worktree, its lock and its link
    python tools/web_node_modules.py link <worktree>   # install if needed, then link
    python tools/web_node_modules.py unlink <worktree> # remove the link before `git worktree remove`
    python tools/web_node_modules.py adopt <web dir>   # move a complete install into the store

`<worktree>` is the planning/product directory of a worktree. The store is
%LOCALAPPDATA%/specplan-web-deps unless WEB_DEPS_STORE is set. `status` exits 1 when any link
points into a worktree, at an install for a different lockfile, at a missing target, or anywhere
outside the store.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PRODUCT = REPO / "planning" / "product"
MARKER = ".install-ok.json"
LOCK_FILES = ("package.json", "package-lock.json")


def store_root() -> Path:
    override = os.environ.get("WEB_DEPS_STORE", "").strip()
    if override:
        return Path(override)
    base = os.environ.get("LOCALAPPDATA", "").strip()
    return (Path(base) if base else Path.home() / ".cache") / "specplan-web-deps"


def lock_hash(web_dir: Path) -> str | None:
    lock = web_dir / "package-lock.json"
    if not lock.is_file():
        return None
    return hashlib.sha256(lock.read_bytes()).hexdigest()


def store_entry(digest: str, root: Path | None = None) -> Path:
    return (root or store_root()) / digest[:16]


def is_link(path: Path) -> bool:
    return path.is_symlink() or (hasattr(os.path, "isjunction") and os.path.isjunction(path))


def link_target(path: Path) -> Path | None:
    if not is_link(path):
        return None
    try:
        raw = os.readlink(path)
    except OSError:
        return None
    # Windows reports junction targets with the \\?\ long-path prefix; compare plain paths.
    return Path(raw[4:] if raw.startswith("\\\\?\\") else raw)


def same_dir(a: Path, b: Path) -> bool:
    return os.path.normcase(os.path.abspath(a)) == os.path.normcase(os.path.abspath(b))


def remove_link(path: Path) -> None:
    """Remove a junction or symlink itself; its target is never touched."""
    if os.name == "nt":
        os.rmdir(path)
    else:
        os.unlink(path)


def missing_packages(web_dir: Path, node_modules: Path | None = None) -> list[str]:
    """Lockfile packages with no installed package.json. Optional ones are skipped: npm installs
    only the platform's own optional binaries, so the others are absent on every machine."""
    lock = json.loads((web_dir / "package-lock.json").read_text(encoding="utf-8"))
    base = node_modules or web_dir / "node_modules"
    missing = []
    for key, meta in lock.get("packages", {}).items():
        if not key.startswith("node_modules/") or meta.get("optional"):
            continue
        if not (base / key[len("node_modules/") :] / "package.json").is_file():
            missing.append(key)
    return missing


def install_ok(entry: Path, digest: str) -> bool:
    marker = entry / MARKER
    if not marker.is_file():
        return False
    try:
        return json.loads(marker.read_text(encoding="utf-8")).get("lock_sha256") == digest
    except ValueError:
        return False


def write_marker(entry: Path, digest: str, source: str) -> None:
    tmp = entry / (MARKER + ".tmp")
    tmp.write_text(json.dumps({"lock_sha256": digest, "source": source}, indent=1), encoding="utf-8")
    os.replace(tmp, entry / MARKER)


def make_dir_link(link: Path, target: Path) -> None:
    if os.name == "nt":
        import _winapi

        _winapi.CreateJunction(str(target), str(link))
    else:
        os.symlink(target, link, target_is_directory=True)


def worktrees() -> list[Path]:
    out = subprocess.run(
        ["git", "-C", str(PRODUCT), "worktree", "list", "--porcelain"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return [Path(line[len("worktree ") :]) for line in out.splitlines() if line.startswith("worktree ")]


@dataclass(frozen=True)
class LinkState:
    worktree: Path
    digest: str | None
    kind: str  # no-lock | none | own-install | ok | wrong-lock | into-worktree | broken | foreign
    target: Path | None


def classify(worktree: Path, all_worktrees: list[Path], root: Path | None = None) -> LinkState:
    web = worktree / "web"
    digest = lock_hash(web)
    node_modules = web / "node_modules"
    if digest is None:
        return LinkState(worktree, None, "no-lock", None)
    if not is_link(node_modules):
        return LinkState(worktree, digest, "own-install" if node_modules.is_dir() else "none", None)
    target = link_target(node_modules)
    if target is None or not target.is_dir():
        return LinkState(worktree, digest, "broken", target)
    if same_dir(target, store_entry(digest, root) / "node_modules"):
        return LinkState(worktree, digest, "ok", target)
    if is_inside(target, root or store_root()):
        return LinkState(worktree, digest, "wrong-lock", target)
    for other in all_worktrees:
        if is_inside(target, other):
            return LinkState(worktree, digest, "into-worktree", target)
    return LinkState(worktree, digest, "foreign", target)


def is_inside(path: Path, parent: Path) -> bool:
    child = os.path.normcase(os.path.abspath(path))
    base = os.path.normcase(os.path.abspath(parent))
    return child.startswith(base.rstrip("\\/") + os.sep)


def ensure_installed(web_dir: Path, digest: str, npm: str | None = None) -> Path:
    entry = store_entry(digest)
    if install_ok(entry, digest):
        return entry
    entry.mkdir(parents=True, exist_ok=True)
    for name in LOCK_FILES:
        shutil.copy2(web_dir / name, entry / name)
    npm_bin = npm or shutil.which("npm") or shutil.which("npm.cmd")
    if not npm_bin:
        raise SystemExit("npm not found on PATH; put Node on PATH and run link again")
    subprocess.run([npm_bin, "ci", "--no-audit", "--no-fund"], cwd=entry, check=True)
    gaps = missing_packages(entry)
    if gaps:
        raise SystemExit(f"npm ci left {len(gaps)} lockfile packages missing, e.g. {gaps[:3]}")
    write_marker(entry, digest, "npm ci")
    return entry


def link(worktree: Path) -> str:
    web = worktree / "web"
    digest = lock_hash(web)
    if digest is None:
        return f"SKIP {worktree}: no web/package-lock.json"
    node_modules = web / "node_modules"
    if node_modules.exists() and not is_link(node_modules):
        return f"SKIP {worktree}: web/node_modules is its own install; delete it to link instead"
    entry = ensure_installed(web, digest)
    if is_link(node_modules):
        remove_link(node_modules)
    make_dir_link(node_modules, entry / "node_modules")
    return f"LINKED {worktree} -> {entry / 'node_modules'}"


def unlink(worktree: Path) -> str:
    node_modules = worktree / "web" / "node_modules"
    if not is_link(node_modules):
        return f"SKIP {worktree}: web/node_modules is not a link"
    remove_link(node_modules)
    return f"UNLINKED {worktree}"


def adopt(web_dir: Path, all_worktrees: list[Path]) -> list[str]:
    """Move a complete install into the store and re-point every link that targeted it."""
    digest = lock_hash(web_dir)
    source = web_dir / "node_modules"
    if digest is None or is_link(source) or not source.is_dir():
        raise SystemExit(f"{web_dir} has no package-lock.json or no install of its own")
    gaps = missing_packages(web_dir)
    if gaps:
        raise SystemExit(f"{len(gaps)} lockfile packages missing from {source}, e.g. {gaps[:3]}; not adopting")
    entry = store_entry(digest)
    if install_ok(entry, digest):
        raise SystemExit(f"store already holds {entry}; link the worktrees instead")
    dependants = [w for w in all_worktrees if (t := link_target(w / "web" / "node_modules")) and same_dir(t, source)]
    entry.mkdir(parents=True, exist_ok=True)
    for name in LOCK_FILES:
        shutil.copy2(web_dir / name, entry / name)
    os.replace(source, entry / "node_modules")  # same volume: a rename, so nothing is copied or lost
    write_marker(entry, digest, f"adopted from {source}")
    lines = [f"ADOPTED {source} -> {entry / 'node_modules'}"]
    for worktree in dependants:
        remove_link(worktree / "web" / "node_modules")
        make_dir_link(worktree / "web" / "node_modules", entry / "node_modules")
        lines.append(f"RELINKED {worktree} -> {entry / 'node_modules'}")
    return lines


def status() -> int:
    trees = worktrees()
    bad = 0
    for tree in trees:
        state = classify(tree, trees)
        lock = state.digest[:12] if state.digest else "-"
        target = f" -> {state.target}" if state.target else ""
        print(f"{state.kind:13} lock {lock}  {tree}{target}")
        bad += state.kind in ("wrong-lock", "into-worktree", "broken", "foreign")
    print(f"store {store_root()}")
    if store_root().is_dir():
        for entry in sorted(store_root().iterdir()):
            print(f"  {entry.name} {'complete' if (entry / MARKER).is_file() else 'INCOMPLETE'}")
    print("WEB_DEPS_OK" if not bad else f"WEB_DEPS_ATTENTION {bad} worktree link(s) to fix with: link <worktree>")
    return 1 if bad else 0


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    command = args.pop(0) if args else "status"
    if command == "status":
        return status()
    if command in ("link", "unlink", "adopt") and len(args) == 1:
        target = Path(args[0])
        if command == "link":
            print(link(target))
        elif command == "unlink":
            print(unlink(target))
        else:
            print("\n".join(adopt(target, worktrees())))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
