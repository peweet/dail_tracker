"""tools/web_node_modules.py: one store install per lockfile, linked into worktrees.

2026-11-08: removing a worktree deleted packages another worktree used through a junction into it,
and four worktrees linked the primary checkout's install for a different lockfile.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

_REPO = Path(__file__).resolve().parents[2]
_SPEC = importlib.util.spec_from_file_location("web_node_modules", _REPO / "tools" / "web_node_modules.py")
wnm = importlib.util.module_from_spec(_SPEC)
sys.modules["web_node_modules"] = wnm  # dataclasses resolve the module by name
_SPEC.loader.exec_module(wnm)


def _lock(packages: dict) -> str:
    return json.dumps({"name": "web", "lockfileVersion": 3, "packages": {"": {}, **packages}})


def _web(root: Path, name: str, lock_text: str, installed: tuple[str, ...] = ()) -> Path:
    """A worktree whose web/ holds package files and, optionally, an install of its own."""
    worktree = root / name / "planning" / "product"
    web = worktree / "web"
    web.mkdir(parents=True)
    (web / "package.json").write_text('{"name": "web"}', encoding="utf-8")
    (web / "package-lock.json").write_text(lock_text, encoding="utf-8")
    for package in installed:
        (web / "node_modules" / package).mkdir(parents=True)
        (web / "node_modules" / package / "package.json").write_text("{}", encoding="utf-8")
    return worktree


LOCK = _lock(
    {
        "node_modules/next": {"version": "16.4.3"},
        "node_modules/@babel/core": {"version": "7.29.7"},
        "node_modules/@esbuild/linux-x64": {"version": "0.28.2", "optional": True},
    }
)


@pytest.fixture
def store(tmp_path, monkeypatch):
    root = tmp_path / "store"
    monkeypatch.setenv("WEB_DEPS_STORE", str(root))
    return root


def test_missing_packages_names_required_gaps_and_ignores_other_platforms(tmp_path):
    tree = _web(tmp_path, "a", LOCK, installed=("next",))
    assert wnm.missing_packages(tree / "web") == ["node_modules/@babel/core"]


def test_adopt_moves_a_complete_install_and_relinks_every_dependant(tmp_path, store):
    source = _web(tmp_path, "source", LOCK, installed=("next", "@babel/core"))
    dependant = _web(tmp_path, "dependant", LOCK)
    wnm.make_dir_link(dependant / "web" / "node_modules", source / "web" / "node_modules")

    lines = wnm.adopt(source / "web", [source, dependant])

    entry = wnm.store_entry(wnm.lock_hash(source / "web"))
    assert lines[0].startswith("ADOPTED") and lines[1].startswith("RELINKED")
    assert (entry / "node_modules" / "next" / "package.json").is_file()
    assert not (source / "web" / "node_modules").exists()
    assert wnm.install_ok(entry, wnm.lock_hash(source / "web"))
    assert wnm.classify(dependant, [source, dependant]).kind == "ok"


def test_adopt_refuses_an_incomplete_install(tmp_path, store):
    source = _web(tmp_path, "source", LOCK, installed=("next",))
    with pytest.raises(SystemExit, match="missing"):
        wnm.adopt(source / "web", [source])
    assert (source / "web" / "node_modules" / "next").is_dir()


def test_classify_flags_links_into_another_worktree_and_to_another_lock(tmp_path, store):
    owner = _web(tmp_path, "owner", LOCK, installed=("next", "@babel/core"))
    borrower = _web(tmp_path, "borrower", LOCK)
    wnm.make_dir_link(borrower / "web" / "node_modules", owner / "web" / "node_modules")
    trees = [owner, borrower]
    assert wnm.classify(borrower, trees).kind == "into-worktree"
    assert wnm.classify(owner, trees).kind == "own-install"

    other = wnm.store_entry("f" * 64) / "node_modules"
    other.mkdir(parents=True)
    wnm.remove_link(borrower / "web" / "node_modules")
    wnm.make_dir_link(borrower / "web" / "node_modules", other)
    assert wnm.classify(borrower, trees).kind == "wrong-lock"


def test_link_reuses_a_complete_store_entry_and_replaces_a_stale_link(tmp_path, store, monkeypatch):
    tree = _web(tmp_path, "tree", LOCK)
    digest = wnm.lock_hash(tree / "web")
    entry = wnm.store_entry(digest)
    (entry / "node_modules" / "next").mkdir(parents=True)
    wnm.write_marker(entry, digest, "test")
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    wnm.make_dir_link(tree / "web" / "node_modules", elsewhere)
    monkeypatch.setattr(wnm.subprocess, "run", lambda *a, **k: pytest.fail("npm must not run for a complete entry"))

    assert wnm.link(tree).startswith("LINKED")
    assert wnm.classify(tree, [tree]).kind == "ok"
    assert elsewhere.is_dir()  # the old target is untouched


def test_link_leaves_an_own_install_alone(tmp_path, store):
    tree = _web(tmp_path, "tree", LOCK, installed=("next",))
    assert wnm.link(tree).startswith("SKIP")
    assert (tree / "web" / "node_modules" / "next").is_dir()


def test_unlink_removes_only_the_link(tmp_path, store):
    owner = _web(tmp_path, "owner", LOCK, installed=("next", "@babel/core"))
    borrower = _web(tmp_path, "borrower", LOCK)
    wnm.make_dir_link(borrower / "web" / "node_modules", owner / "web" / "node_modules")
    assert wnm.unlink(borrower).startswith("UNLINKED")
    assert not (borrower / "web" / "node_modules").exists()
    assert (owner / "web" / "node_modules" / "next" / "package.json").is_file()
